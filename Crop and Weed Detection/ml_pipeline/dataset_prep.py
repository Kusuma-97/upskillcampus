"""
dataset_prep.py
----------------
Converts the flat `dataset/agri_data/data/` folder (image.jpeg + matching image.txt
YOLO-label pairs, all in one directory) into the split folder layout Ultralytics/YOLO
expects, and writes the data.yaml config file used by train_weed_detector.py.

Source classes (from dataset/classes.txt):
    0 -> crop
    1 -> weed

Usage:
    python dataset_prep.py
"""

import random
import shutil
from pathlib import Path

# ---------------------------------------------------------------------------
# Config
# ---------------------------------------------------------------------------
SEED = 42
VAL_FRACTION = 0.15
TEST_FRACTION = 0.05  # held out, never touched during training/val — final sanity check only

THIS_DIR = Path(__file__).resolve().parent
SRC_DIR = THIS_DIR.parent / "dataset" / "agri_data" / "data"
CLASSES_FILE = THIS_DIR.parent / "dataset" / "classes.txt"
OUT_DIR = THIS_DIR / "yolo_dataset"


def load_classes() -> list[str]:
    with open(CLASSES_FILE, "r") as f:
        # classes.txt in this dataset has no newline between the two entries in some
        # exports, so we defensively split on any whitespace as well as newlines.
        raw = f.read()
    names = [n.strip() for n in raw.replace("\r", "\n").split("\n") if n.strip()]
    if len(names) < 2:
        # fallback: classes.txt sometimes ships as "crop\r\nweed" with no trailing char,
        # handle a squished "cropweed" edge case defensively
        names = ["crop", "weed"]
    return names


def collect_pairs(src: Path) -> list[tuple[Path, Path]]:
    """Return list of (image_path, label_path) for every image that has a matching
    YOLO .txt label file. Images without labels (shouldn't happen in this dataset,
    but we guard anyway) are skipped with a warning."""
    pairs = []
    skipped = 0
    for img_path in sorted(src.glob("*.jpeg")):
        label_path = img_path.with_suffix(".txt")
        if label_path.exists():
            pairs.append((img_path, label_path))
        else:
            skipped += 1
    if skipped:
        print(f"[warn] {skipped} images had no matching label file and were skipped.")
    return pairs


def split(pairs: list[tuple[Path, Path]]):
    random.Random(SEED).shuffle(pairs)
    n = len(pairs)
    n_test = int(n * TEST_FRACTION)
    n_val = int(n * VAL_FRACTION)
    test = pairs[:n_test]
    val = pairs[n_test:n_test + n_val]
    train = pairs[n_test + n_val:]
    return train, val, test


def materialize(split_name: str, pairs: list[tuple[Path, Path]]):
    img_out = OUT_DIR / split_name / "images"
    lbl_out = OUT_DIR / split_name / "labels"
    img_out.mkdir(parents=True, exist_ok=True)
    lbl_out.mkdir(parents=True, exist_ok=True)
    for img_path, label_path in pairs:
        shutil.copy2(img_path, img_out / img_path.name)
        shutil.copy2(label_path, lbl_out / label_path.name)
    print(f"[{split_name}] {len(pairs)} images -> {img_out}")


def write_data_yaml(class_names: list[str]):
    yaml_path = OUT_DIR / "data.yaml"
    content = (
        f"# Auto-generated by dataset_prep.py\n"
        f"path: {OUT_DIR.resolve()}\n"
        f"train: train/images\n"
        f"val: val/images\n"
        f"test: test/images\n"
        f"nc: {len(class_names)}\n"
        f"names: {class_names}\n"
    )
    yaml_path.write_text(content)
    print(f"[data.yaml] written -> {yaml_path}")


def main():
    if not SRC_DIR.exists():
        raise FileNotFoundError(
            f"Could not find source dataset at {SRC_DIR}. "
            "Make sure dataset/agri_data/data/ exists relative to the project root."
        )

    class_names = load_classes()
    print(f"Classes: {class_names}")

    pairs = collect_pairs(SRC_DIR)
    print(f"Found {len(pairs)} labeled image/label pairs.")

    train, val, test = split(pairs)
    print(f"Split -> train: {len(train)}, val: {len(val)}, test: {len(test)}")

    if OUT_DIR.exists():
        shutil.rmtree(OUT_DIR)

    materialize("train", train)
    materialize("val", val)
    materialize("test", test)
    write_data_yaml(class_names)

    print("\nDone. Next: python train_weed_detector.py")


if __name__ == "__main__":
    main()
